#!/usr/bin/env python3
"""Analyze R1h conv1 byte0 window-vs-weight mapping isolation.

This script post-processes the R1h focused trace generated by
tb_resnet20_r1h_package_compare.  It does not run RTL and does not change any
golden/reference data; it only computes deterministic MAC cross-products to
separate window extraction issues from weight mapping issues.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="ascii"))


def mac_sum(inputs: list[int], weights: list[int]) -> int:
    return sum(int(x) * int(w) for x, w in zip(inputs, weights))


def main() -> int:
    parser = argparse.ArgumentParser(description="Analyze R1h conv1 window/weight isolation trace")
    parser.add_argument("--trace", default="tb/generated/resnet20_r1h_conv1_trace.json")
    parser.add_argument("--debug-summary", default="tb/generated/resnet20_r1h_package_compare_debug_summary.json")
    parser.add_argument("--output", default="tb/generated/resnet20_r1h_conv1_window_weight_isolation.json")
    args = parser.parse_args()

    trace = load_json(Path(args.trace))
    debug_summary = load_json(Path(args.debug_summary))

    ref_taps = trace["reference"]["taps"]
    rtl_taps = trace["rtl"]["taps"]
    if len(ref_taps) != len(rtl_taps):
        raise SystemExit(f"tap count mismatch: ref={len(ref_taps)} rtl={len(rtl_taps)}")

    ref_inputs = [int(tap["input_i8"]) for tap in ref_taps]
    ref_weights = [int(tap["weight_i8"]) for tap in ref_taps]
    rtl_inputs = [int(tap["window_i8"]) for tap in rtl_taps]
    rtl_weights = [int(tap["weight_i8"]) for tap in rtl_taps]

    variants = {
        "reference_window_reference_weight": mac_sum(ref_inputs, ref_weights),
        "rtl_window_rtl_weight": mac_sum(rtl_inputs, rtl_weights),
        "rtl_window_reference_weight": mac_sum(rtl_inputs, ref_weights),
        "reference_window_rtl_weight": mac_sum(ref_inputs, rtl_weights),
        "rtl_reported_mac_before_bias": int(trace["rtl"]["mac_before_bias"]),
        "reference_reported_mac_before_bias": int(trace["reference"]["mac_before_bias"]),
    }

    window_diffs: list[dict[str, Any]] = []
    weight_diffs: list[dict[str, Any]] = []
    for idx, (ref_tap, rtl_tap) in enumerate(zip(ref_taps, rtl_taps)):
        if int(ref_tap["input_i8"]) != int(rtl_tap["window_i8"]):
            window_diffs.append({
                "tap": idx,
                "kh": int(ref_tap["kh"]) if "kh" in ref_tap else None,
                "kw": int(ref_tap["kw"]) if "kw" in ref_tap else None,
                "ic": int(ref_tap["ic"]) if "ic" in ref_tap else None,
                "reference_input_idx": int(ref_tap["input_idx"]),
                "reference_input_i8": int(ref_tap["input_i8"]),
                "rtl_window_i8": int(rtl_tap["window_i8"]),
                "rtl_window_byte": rtl_tap["window_byte"],
            })
        if int(ref_tap["weight_i8"]) != int(rtl_tap["weight_i8"]):
            weight_diffs.append({
                "tap": idx,
                "reference_weight_idx": int(ref_tap["weight_idx"]),
                "reference_weight_i8": int(ref_tap["weight_i8"]),
                "rtl_weight_i8": int(rtl_tap["weight_i8"]),
                "rtl_weight_byte": rtl_tap["weight_byte"],
            })

    same_padding_boundary_check = {
        "position": trace["position"],
        "expected_top_row_taps_zero": all(ref_inputs[idx] == 0 for idx in range(0, 9)),
        "expected_left_col_taps_zero": all(ref_inputs[idx] == 0 for idx in [0, 1, 2, 9, 10, 11, 18, 19, 20]),
        "reference_first_valid_pixel_taps": [
            {"tap": idx, **ref_taps[idx]} for idx in [12, 13, 14, 15, 16, 17, 21, 22, 23, 24, 25, 26]
        ],
        "rtl_first_valid_pixel_observation": [
            {"tap": idx, **rtl_taps[idx]} for idx in [12, 13, 14, 15, 16, 17, 21, 22, 23, 24, 25, 26]
        ],
        "interpretation": (
            "For output(0,0,0), reference same-padding maps input[0..5] to center/right taps "
            "12..17 and input[96..101] to lower center/right taps 21..26. RTL observed taps "
            "12..17 remain zero and input[0..5] appears at taps 21..26, indicating a one-row "
            "window placement shift at the top boundary."
        ),
    }

    if not weight_diffs and window_diffs:
        preferred_root_cause = "input_window_extraction_bug"
    elif weight_diffs and not window_diffs:
        preferred_root_cause = "weight_mapping_bug"
    elif weight_diffs and window_diffs:
        preferred_root_cause = "both_possible_but_not_yet_separated"
    else:
        preferred_root_cause = "not_reproduced_by_tap_value_comparison"

    output = {
        "scope": "R1h full-shape conv1 output(0,0,0) window/weight isolation",
        "source_trace": args.trace,
        "source_debug_summary": args.debug_summary,
        "first_mismatch": {
            "byte_index": 0,
            "expected": trace["reference"]["output_byte"],
            "actual": trace["rtl"]["stored_output_bytes_0_3"][0],
        },
        "recomputed_mac_variants": variants,
        "window_diff_count": len(window_diffs),
        "weight_diff_count": len(weight_diffs),
        "window_diffs": window_diffs,
        "weight_diffs": weight_diffs,
        "same_padding_boundary_check": same_padding_boundary_check,
        "rtl_captured_tap_sum_matches_rtl_reported_mac": (
            variants["rtl_window_rtl_weight"] == variants["rtl_reported_mac_before_bias"]
        ),
        "preferred_root_cause": preferred_root_cause,
        "root_cause_note": (
            "Observed weight taps match the reference order for this position, while window taps diverge at "
            "the top-boundary same-padding transition. The captured RTL tap sum does not equal the final "
            "RTL reported MAC, so a follow-up should also verify which exact fed window/accumulator address "
            "produces acc_buffer[0]."
        ),
        "unknown_byte64_independent": {
            "first_unknown_idx": debug_summary.get("first_unknown_idx"),
            "first_unknown_position_dense_hwc": debug_summary.get("first_unknown_position_dense_hwc"),
            "affects_byte0_conclusion": False,
        },
        "not_full_resnet20": True,
    }

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(output, indent=2, sort_keys=True) + "\n", encoding="ascii")
    print(f"Wrote {output_path}")
    print(f"preferred_root_cause={preferred_root_cause}")
    print(f"window_diff_count={len(window_diffs)} weight_diff_count={len(weight_diffs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
