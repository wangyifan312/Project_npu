#!/usr/bin/env python3
"""Generate a small package-derived RTL smoke stimulus for R1f.

The output is a Verilog include consumed by tb_resnet20_r1f_smoke.v.  It does
not attempt full ResNet execution; it extracts a representative Conv/ADD/GAP/FC
slice from the validated R0.5 handoff package.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


DEFAULT_SLICE = [
    "layer1.0.conv1",
    "layer1.0.conv2",
    "layer1.0.add",
    "gap",
    "fc",
]

RESIDUAL_NPU_TOP_SLICE = [
    "layer1.0.conv1",
    "layer1.0.conv2",
    "layer1.0.add",
]

RESIDUAL_ALIAS_ADDR = {
    "conv1.relu": 0x0000_1000,
    "layer1.0.conv1.relu": 0x0000_2000,
    "layer1.0.conv2.pre_add_main": 0x0000_3000,
    "layer1.0.add.relu": 0x0000_4000,
}

RESIDUAL_ALIAS_BYTES = {
    "conv1.relu": 36,
    "layer1.0.conv1.relu": 36,
    "layer1.0.conv2.pre_add_main": 36,
    "layer1.0.add.relu": 36,
}

RESIDUAL_WEIGHT_ALIAS_BASE = 0x0000_8000
RESIDUAL_BIAS_ALIAS_BASE = 0x0000_C000


def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def memh_values(path: Path) -> list[int]:
    values: list[int] = []
    with path.open("r", encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("//"):
                continue
            values.append(int(line, 16))
    return values


def checksum_memh(path: Path) -> int:
    acc = 0
    for idx, value in enumerate(memh_values(path), start=1):
        acc = (acc + ((value & 0xFFFFFFFF) * idx)) & 0xFFFFFFFF
    return acc


def align64(value: int) -> int:
    return (value + 63) & ~63


def shape_to_hwc(shape: list[int]) -> tuple[int, int, int]:
    if len(shape) == 3:
        c, h, w = shape
        return int(h), int(w), int(c)
    if len(shape) == 1:
        return 1, 1, int(shape[0])
    raise ValueError(f"unsupported shape: {shape}")


def tensor_byte_size(tensor: dict[str, Any]) -> int:
    return int(tensor["byte_size"])


def conv_cfg_for(task: dict[str, Any]) -> int:
    op_type = task["op_type"]
    if op_type == "CONV3x3":
        kernel_sel = 2
        same = 1
    elif op_type == "CONV1x1_PROJECTION":
        kernel_sel = 1
        same = 0
    else:
        return 0
    stride2 = 1 if int(task.get("stride") or 1) == 2 else 0
    bias_en = 1 if task.get("bias_file") else 0
    projection = 1 if op_type == "CONV1x1_PROJECTION" else 0
    return (
        kernel_sel
        | (stride2 << 2)
        | (same << 3)
        | (bias_en << 4)
        | (projection << 5)
    )


def find_item(items: list[dict[str, Any]], op: str) -> dict[str, Any]:
    for item in items:
        if item.get("op") == op:
            return item
    raise KeyError(op)


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_include(path: Path, tasks: list[dict[str, Any]], tensors: list[dict[str, Any]], final_checksum: int) -> None:
    max_tasks = len(tasks)
    max_tensors = len(tensors)
    lines: list[str] = []
    lines.append("// Generated by datasets/scripts/extract_resnet20_r1f_smoke.py")
    lines.append("// R1f smoke only: package-derived subset, not full ResNet-20 execution.")
    lines.append(f"localparam integer R1F_TASK_COUNT = {max_tasks};")
    lines.append(f"localparam integer R1F_TENSOR_COUNT = {max_tensors};")
    lines.append(f"localparam [31:0] R1F_EXPECTED_FINAL_CHECKSUM = 32'h{final_checksum:08x};")
    lines.append("")
    lines.append("task init_r1f_smoke_tasks;")
    lines.append("begin")
    for idx, tensor in enumerate(tensors):
        lines.append(f"    r1f_tensor_name[{idx}] = {q(tensor['name'])};")
        lines.append(f"    r1f_tensor_addr[{idx}] = 32'd{tensor['base_addr']};")
        lines.append(f"    r1f_tensor_bytes[{idx}] = 32'd{tensor['byte_size']};")
        lines.append(f"    r1f_tensor_checksum[{idx}] = 32'h{tensor['seed_checksum']:08x};")
    for idx, task in enumerate(tasks):
        lines.append(f"    r1f_task_name[{idx}] = {q(task['name'])};")
        lines.append(f"    r1f_op_name[{idx}] = {q(task['op_type'])};")
        for key in [
            "task_type",
            "input_addr",
            "weight_addr",
            "output_addr",
            "input_bytes",
            "weight_bytes",
            "output_bytes",
            "input_h",
            "input_w",
            "input_c",
            "output_c",
            "conv_cfg",
            "bias_addr",
            "bias_bytes",
            "src1_addr",
            "src1_bytes",
            "add_cfg",
            "gap_cfg",
            "postproc_cfg",
            "requant_multiplier",
            "requant_shift",
            "add_src0_multiplier",
            "add_src0_shift",
            "add_src1_multiplier",
            "add_src1_shift",
            "add_out_multiplier",
            "add_out_shift",
            "src0_tensor_idx",
            "src1_tensor_idx",
            "dst_tensor_idx",
            "weight_checksum",
            "bias_checksum",
            "expected_output_checksum",
        ]:
            value = task[key]
            if key.endswith("_idx") and value < 0:
                lines.append(f"    r1f_{key}[{idx}] = -1;")
            elif key.endswith("checksum"):
                lines.append(f"    r1f_{key}[{idx}] = 32'h{value & 0xFFFFFFFF:08x};")
            else:
                lines.append(f"    r1f_{key}[{idx}] = 32'd{value};")
    lines.append("end")
    lines.append("endtask")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def compact_shape_for(task: dict[str, Any]) -> tuple[int, int, int, int]:
    if task["op_type"] == "CONV3x3":
        return 3, 3, 1, 1
    if task["op_type"] == "RESIDUAL_ADD":
        return 1, 1, 36, 36
    in_h, in_w, in_c = shape_to_hwc(task["input_shape"])
    _out_h, _out_w, out_c = shape_to_hwc(task["output_shape"])
    return in_h, in_w, in_c, out_c


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--package-dir", default="datasets/cifar10/resnet20_export_package")
    ap.add_argument("--output", default="tb/generated/resnet20_r1f_smoke_tasks.vh")
    ap.add_argument("--summary", default="tb/generated/resnet20_r1f_smoke_summary.json")
    ap.add_argument(
        "--slice-mode",
        choices=["control_checker", "residual_npu_top"],
        default="control_checker",
    )
    args = ap.parse_args()

    package_dir = Path(args.package_dir)
    task_sequence = load_json(package_dir / "task_sequence.json")
    memory_map = load_json(package_dir / "memory_map.json")
    conv_fc = load_json(package_dir / "requant/conv_fc_requant.json")["items"]
    residual = load_json(package_dir / "requant/residual_add_alignment.json")["items"]
    gap_req_path = package_dir / "requant/gap_requant.json"
    gap_req = load_json(gap_req_path) if gap_req_path.exists() else {}

    task_by_name = {t["name"]: t for t in task_sequence["tasks"]}
    tensor_by_name = {t["name"]: t for t in memory_map["tensors"]}

    slice_names = RESIDUAL_NPU_TOP_SLICE if args.slice_mode == "residual_npu_top" else DEFAULT_SLICE
    use_compact_alias = args.slice_mode == "residual_npu_top"
    selected_tasks = [task_by_name[name] for name in slice_names]
    tensor_names: list[str] = []
    for task in selected_tasks:
        for name in task.get("input_tensors", []):
            if name not in tensor_names:
                tensor_names.append(name)
        out = task["output_tensor"]
        if out not in tensor_names:
            tensor_names.append(out)

    tensors: list[dict[str, Any]] = []
    tensor_idx = {name: idx for idx, name in enumerate(tensor_names)}
    for name in tensor_names:
        src = tensor_by_name[name]
        base_addr = RESIDUAL_ALIAS_ADDR[name] if use_compact_alias else int(src["base_addr"])
        byte_size = RESIDUAL_ALIAS_BYTES[name] if use_compact_alias else int(src["byte_size"])
        seed = (
            (base_addr * 2654435761)
            ^ (byte_size * 2246822519)
            ^ sum(ord(c) for c in name)
        ) & 0xFFFFFFFF
        tensors.append(
            {
                "name": name,
                "base_addr": base_addr,
                "byte_size": byte_size,
                "package_base_addr": int(src["base_addr"]),
                "package_byte_size": int(src["byte_size"]),
                "seed_checksum": seed,
            }
        )

    weight_base = RESIDUAL_WEIGHT_ALIAS_BASE if use_compact_alias else 0x0009_0000
    bias_base = RESIDUAL_BIAS_ALIAS_BASE if use_compact_alias else 0x000A_8000
    weight_cursor = weight_base
    bias_cursor = bias_base

    emitted: list[dict[str, Any]] = []
    checksum_by_tensor = {idx: tensors[idx]["seed_checksum"] for idx in range(len(tensors))}

    for task in selected_tasks:
        op = task["op_type"]
        inputs = task.get("input_tensors", [])
        src0_idx = tensor_idx[inputs[0]] if inputs else -1
        src1_idx = tensor_idx[inputs[1]] if len(inputs) > 1 else -1
        dst_idx = tensor_idx[task["output_tensor"]]
        in_h, in_w, in_c = shape_to_hwc(task["input_shape"])
        out_h, out_w, out_c = shape_to_hwc(task["output_shape"])
        if use_compact_alias:
            in_h, in_w, in_c, out_c = compact_shape_for(task)

        weight_file = task.get("weight_file")
        bias_file = task.get("bias_file")
        weight_values = memh_values(package_dir / weight_file) if weight_file else []
        bias_values = memh_values(package_dir / bias_file) if bias_file else []
        weight_checksum = checksum_memh(package_dir / weight_file) if weight_file else 0
        bias_checksum = checksum_memh(package_dir / bias_file) if bias_file else 0

        weight_addr = 0
        bias_addr = 0
        if weight_file:
            weight_addr = weight_cursor
            compact_weight_bytes = 12 if use_compact_alias and op == "CONV3x3" else len(weight_values)
            weight_cursor = align64(weight_cursor + compact_weight_bytes)
        if bias_file:
            bias_addr = bias_cursor
            compact_bias_bytes = 4 if use_compact_alias and op == "CONV3x3" else len(bias_values) * 4
            bias_cursor = align64(bias_cursor + compact_bias_bytes)

        task_type = {"CONV3x3": 0, "CONV1x1_PROJECTION": 0, "RESIDUAL_ADD": 4, "GAP8x8": 5, "FC10": 1}[op]
        conv_cfg = conv_cfg_for(task)
        if op == "FC10" and bias_file:
            conv_cfg |= 0x10
        add_cfg = 0
        gap_cfg = 0
        postproc_cfg = 0
        rq_mult = 1
        rq_shift = 0
        add_src0_mult = 1
        add_src0_shift = 0
        add_src1_mult = 1
        add_src1_shift = 0
        add_out_mult = 1
        add_out_shift = 0

        if op in ("CONV3x3", "CONV1x1_PROJECTION", "FC10"):
            item = find_item(conv_fc, task["name"])
            rq_mult = int(item["requant"]["multiplier_int"])
            rq_shift = int(item["requant"]["shift"])
        elif op == "RESIDUAL_ADD":
            item = find_item(residual, task["name"])
            add_cfg = 0x4  # R1f smoke uses ADD+ReLU; post-requant remains R1g numerical work.
            add_src0_mult = int(item["main_to_target"]["multiplier_int"])
            add_src0_shift = int(item["main_to_target"]["shift"])
            add_src1_mult = int(item["shortcut_to_target"]["multiplier_int"])
            add_src1_shift = int(item["shortcut_to_target"]["shift"])
        elif op == "GAP8x8":
            gap_cfg = 6 << 20
            postproc_cfg = 0x2
            rq_mult = int(gap_req["requant"]["multiplier_int"])
            rq_shift = int(gap_req["requant"]["shift"])

        src0_checksum = checksum_by_tensor.get(src0_idx, 0)
        src1_checksum = checksum_by_tensor.get(src1_idx, 0)
        expected = (
            src0_checksum
            ^ ((src1_checksum << 1) & 0xFFFFFFFF)
            ^ weight_checksum
            ^ ((bias_checksum << 3) & 0xFFFFFFFF)
            ^ int(task["task_id"])
            ^ (task_type << 24)
            ^ rq_mult
            ^ (rq_shift << 16)
        ) & 0xFFFFFFFF
        checksum_by_tensor[dst_idx] = expected

        emitted.append(
            {
                "name": task["name"],
                "op_type": op,
                "task_type": task_type,
                "input_addr": tensors[src0_idx]["base_addr"] if inputs else 0,
                "weight_addr": weight_addr,
                "output_addr": tensors[dst_idx]["base_addr"],
                "input_bytes": tensors[src0_idx]["byte_size"] if inputs else 0,
                "weight_bytes": (12 if use_compact_alias and op == "CONV3x3" else len(weight_values)),
                "output_bytes": tensors[dst_idx]["byte_size"],
                "input_h": in_h,
                "input_w": in_w,
                "input_c": in_c,
                "output_c": out_c,
                "conv_cfg": conv_cfg,
                "bias_addr": bias_addr,
                "bias_bytes": (4 if use_compact_alias and op == "CONV3x3" else len(bias_values) * 4),
                "src1_addr": tensors[src1_idx]["base_addr"] if len(inputs) > 1 else 0,
                "src1_bytes": tensors[src1_idx]["byte_size"] if len(inputs) > 1 else 0,
                "add_cfg": add_cfg,
                "gap_cfg": gap_cfg,
                "postproc_cfg": postproc_cfg,
                "requant_multiplier": rq_mult,
                "requant_shift": rq_shift,
                "add_src0_multiplier": add_src0_mult,
                "add_src0_shift": add_src0_shift,
                "add_src1_multiplier": add_src1_mult,
                "add_src1_shift": add_src1_shift,
                "add_out_multiplier": add_out_mult,
                "add_out_shift": add_out_shift,
                "src0_tensor_idx": src0_idx,
                "src1_tensor_idx": src1_idx,
                "dst_tensor_idx": dst_idx,
                "weight_checksum": weight_checksum,
                "bias_checksum": bias_checksum,
                "expected_output_checksum": expected,
                "input_tensors": inputs,
                "output_tensor": task["output_tensor"],
                "weight_file": weight_file,
                "bias_file": bias_file,
            }
        )

    final_checksum = emitted[-1]["expected_output_checksum"]
    emit_include(Path(args.output), emitted, tensors, final_checksum)

    summary = {
        "status": "generated",
        "scope": "R1f task-sequence RTL smoke stimulus, not full ResNet-20 execution",
        "slice_mode": args.slice_mode,
        "package_dir": str(package_dir),
        "slice": slice_names,
        "task_count": len(emitted),
        "task_types": [t["task_type"] for t in emitted],
        "tasks": emitted,
        "tensor_count": len(tensors),
        "tensors": tensors,
        "expected_final_checksum": f"0x{final_checksum:08x}",
        "notes": (
            [
                "Continuous early residual slice; no GAP/FC tail splice.",
                "Uses test-only nonzero compact alias addresses/dimensions for npu_top smoke speed.",
                "Package input.image base_addr=0 remains a full-sequence blocker because current task_checker rejects null address.",
            ]
            if use_compact_alias
            else [
                "Starts at task1 to avoid package input.image base_addr=0, which current task_checker rejects as null address.",
                "Residual slice and GAP->FC tail are package-derived but not a full 32-task ResNet sequence.",
            ]
        ),
    }
    Path(args.summary).write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
